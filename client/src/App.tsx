type Language = 'en' | 'el'
type OptionId = 'A' | 'B' | 'C'
type Stage = 'landing' | 'answer' | 'generating' | 'compare' | 'choose' | 'ranking' | 'result'

interface DecisionOption {
  id: OptionId
  title: string
  description: string
}

interface Comparison {
  summary: string
  closestOption: OptionId | null
  overlap: string[]
  gaps: string[]
  insight: string
  isMock: boolean
}

interface GeneratedSession {
  sessionId: string
  options: [DecisionOption, DecisionOption, DecisionOption]
  comparison: Comparison
  isMock: boolean
}

interface Ranking {
  rankedOptions: Array<DecisionOption & { probability: number; rank: number }>
  topOption: OptionId
  confidence: number
  isMock: boolean
}

interface Dashboard {
  responses: number
  distribution: Record<OptionId, number>
  alignmentRate: number
  averageConfidence: number
}

interface Health {
  modelProvider: 'mock' | 'foundry'
}

