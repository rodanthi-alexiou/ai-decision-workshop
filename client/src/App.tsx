const emptyDashboard: Dashboard = {
  responses: 0,
  distribution: { A: 0, B: 0, C: 0 },
  alignmentRate: 0,
  averageConfidence: 0,
}

const percent = (value: number): string => `${Math.round(value * 100)}%`

const tabIndex: Record<Stage, number> = {
  landing: -1,
  answer: 0,
  generating: 0,
  compare: 1,
  choose: 2,
  ranking: 2,
  result: 3,
}

function App() {
  const [language, setLanguage] = useState<Language>('en')
  const [stage, setStage] = useState<Stage>('landing')
  const [userAnswer, setUserAnswer] = useState('')
  const [caseKind, setCaseKind] = useState<'support' | 'custom'>('support')
  const [customScenario, setCustomScenario] = useState('')
  const [generated, setGenerated] = useState<GeneratedSession | null>(null)
  const [selectedOption, setSelectedOption] = useState<OptionId | null>(null)
  const [ranking, setRanking] = useState<Ranking | null>(null)
  const [dashboard, setDashboard] = useState<Dashboard>(emptyDashboard)
  const [health, setHealth] = useState<Health | null>(null)
  const [error, setError] = useState('')
  const facilitator = window.location.pathname.startsWith('/facilitator')
  const t = copy[language]

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  useEffect(() => {
    void fetch('/api/health')
      .then((response) => response.json())
      .then((value: Health) => setHealth(value))
      .catch(() => setHealth(null))
  }, [])

  useEffect(() => {
    if (!facilitator) return
    const refresh = () => {
      void fetch('/api/dashboard')
        .then((response) => response.json())
        .then((value: Dashboard) => setDashboard(value))
        .catch(() => undefined)
    }
    refresh()
    const timer = window.setInterval(refresh, 3000)
    return () => window.clearInterval(timer)
  }, [facilitator])

  const reset = () => {
    setStage('landing')
    setUserAnswer('')
    setCaseKind('support')
    setCustomScenario('')
    setSelectedOption(null)
    setRanking(null)
    setError('')
  }

  const generate = async () => {
    setStage('generating')
    setError('')
    try {
      const response = await fetch('/api/sessions', {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ language, userAnswer, caseId: caseKind, customScenario }),
      })
      if (!response.ok) throw new Error(await response.text())
      setGenerated((await response.json()) as GeneratedSession)
      setStage('compare')
    } catch (requestError) {
      console.error(requestError)
      setError(t.error)
      setStage('answer')
    }
  }

  const rank = async () => {
    if (!generated || !selectedOption) return
    setStage('ranking')
    setError('')
    try {
      const response = await fetch(`/api/sessions/${generated.sessionId}/select`, {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ selectedOption }),
      })
      if (!response.ok) throw new Error(await response.text())
      const value = (await response.json()) as { ranking: Ranking; dashboard: Dashboard }
      setRanking(value.ranking)
      setDashboard(value.dashboard)
      setStage('result')
    } catch (requestError) {
      console.error(requestError)
      setError(t.error)
      setStage('choose')
    }
  }

  if (facilitator) {
    return <FacilitatorView dashboard={dashboard} language={language} setLanguage={setLanguage} />
  }

  const active = tabIndex[stage]
  const reached = stage === 'result' ? 3 : stage === 'choose' || stage === 'ranking' ? 2 : generated ? 1 : 0
  const goTo = (index: number) => {
    if (stage === 'generating' || stage === 'ranking' || index > reached || index === 3) return
    setStage((['answer', 'compare', 'choose'] as const)[index]!)
  }

  return (
    <main className="app-shell">
      <header className="topbar">
        <button className="wordmark" onClick={reset} aria-label="Decision Room home">
          DECISION <span>/ ROOM</span>
        </button>
        <div className="top-actions">
          <span className={`model-pill ${health?.modelProvider === 'foundry' ? 'live' : ''}`}>
            {health?.modelProvider === 'foundry' ? t.live : t.mock}
          </span>
          <button className="language" onClick={() => setLanguage(language === 'en' ? 'el' : 'en')}>
            {language === 'en' ? 'ΕΛ' : 'EN'}
          </button>
        </div>
      </header>

      {stage === 'landing' && (
        <section className="landing">
          <p className="eyebrow reveal r1">{t.kicker}</p>
          <h1 className="landing-title reveal r2">{t.title}</h1>
          <div className="landing-footer reveal r3">
            <div>
              <p>{t.intro}</p>
              <small>{t.privacy}</small>
            </div>
            <button className="primary" onClick={() => setStage('answer')}>
              <span>{t.begin}</span><b>→</b>
            </button>
          </div>
        </section>
      )}

      {stage !== 'landing' && (
        <nav className="tabs" aria-label="Steps">
          {t.tabs.map((label, index) => (
            <button
              key={label}
              className={`tab ${index === active ? 'active' : ''}`}
              disabled={index > reached || index === 3}
              aria-current={index === active ? 'step' : undefined}
              onClick={() => goTo(index)}
            >
              <span>{String(index + 1).padStart(2, '0')}</span>{label}
            </button>
          ))}
        </nav>
      )}

      {stage === 'answer' && (
        <Screen code={caseKind === 'custom' ? 'CUSTOM' : t.company} title={caseKind === 'custom' ? t.ownTitle : t.scenarioTitle}>
          <div className="case-toggle" role="tablist">
            {(['support', 'custom'] as const).map((kind) => (
              <button
                key={kind}
                role="tab"
                aria-selected={caseKind === kind}
                className={caseKind === kind ? 'active' : ''}
                onClick={() => setCaseKind(kind)}
              >
                {kind === 'support' ? t.caseReady : t.caseOwn}
              </button>
            ))}
          </div>
          {caseKind === 'support' ? (
            <p className="scenario">{t.scenario}</p>
          ) : (
            <>
              <p className="guide">{t.ownGuide}</p>
              <label className="action-field">
                <small>{t.ownScenarioLabel}</small>
                <textarea
                  className="tall"
                  value={customScenario}
                  maxLength={1500}
                  placeholder={t.ownScenarioPlaceholder}
                  onChange={(event) => setCustomScenario(event.target.value)}
                  aria-label={t.ownScenarioLabel}
                />
                <span>{customScenario.length}/1500</span>
              </label>
            </>
          )}
          <p className="question">{caseKind === 'custom' ? t.ownPrompt : t.prompt}</p>
          <label className="action-field">
            <textarea
              value={userAnswer}
              maxLength={500}
              placeholder={caseKind === 'custom' ? t.ownAnswerPlaceholder : t.placeholder}
              onChange={(event) => setUserAnswer(event.target.value)}
              aria-label={caseKind === 'custom' ? t.ownPrompt : t.prompt}
            />
            <span>{userAnswer.length}/500</span>
          </label>
          <p className="hint">{caseKind === 'custom' ? t.ownHint : t.answerHint}</p>
          {error && <ErrorPanel text={error} />}
          <Actions>
            <button
              className="primary"
              disabled={!userAnswer.trim() || (caseKind === 'custom' && customScenario.trim().length < 40)}
              title={caseKind === 'custom' && customScenario.trim().length < 40 ? t.ownMin : undefined}
              onClick={() => void generate()}
            >
              <span>{t.generate}</span><b>→</b>
            </button>
          </Actions>
        </Screen>
      )}

      {(stage === 'generating' || stage === 'ranking') && (
        <section className="processing">
          <div className="processor"><div className="processor-ring" /></div>
          <h2>{stage === 'generating' ? t.generatingTitle : t.rankingTitle}</h2>
          {stage === 'generating' && <p>{t.generatingNote}</p>}
        </section>
      )}

      {stage === 'compare' && generated && (
        <Screen code="02" title={t.optionsTitle} intro={t.optionsNote}>
          <div className="option-stack">
            {generated.options.map((option) => (
              <article
                key={option.id}
                className={`option-card static ${generated.comparison.closestOption === option.id ? 'closest' : ''}`}
              >
                <span>{option.id}</span>
                <div><strong>{option.title}</strong><p>{option.description}</p></div>
                {generated.comparison.closestOption === option.id && <i>{t.closest}</i>}
              </article>
            ))}
          </div>
          <section className="compare-panel">
            <p className="panel-label">{t.comparisonTitle}</p>
            <div className="compare-grid">
              <div>
                <small>{t.yourAnswer}</small>
                <blockquote>{userAnswer}</blockquote>
              </div>
              <div>
                <p className="compare-summary">{generated.comparison.summary}</p>
                <small>{t.overlap}</small>
                <ul>
                  {generated.comparison.overlap.length
                    ? generated.comparison.overlap.map((item) => <li key={item}>{item}</li>)
                    : <li>—</li>}
                </ul>
                <small>{t.gaps}</small>
                <ul>{generated.comparison.gaps.map((item) => <li key={item}>{item}</li>)}</ul>
                <small>{t.insight}</small>
                <p>{generated.comparison.insight}</p>
              </div>
            </div>
          </section>
          <Actions>
            <button className="back" onClick={() => setStage('answer')}>← {t.back}</button>
            <button className="primary" onClick={() => setStage('choose')}>
              <span>{t.toChoose}</span><b>→</b>
            </button>
          </Actions>
        </Screen>
      )}

      {stage === 'choose' && generated && (
        <Screen code="03" title={t.chooseTitle} intro={t.chooseNote}>
          <div className="option-stack">
            {generated.options.map((option) => (
              <button
                key={option.id}
                className={`option-card ${selectedOption === option.id ? 'selected' : ''}`}
                aria-pressed={selectedOption === option.id}
                onClick={() => setSelectedOption(option.id)}
              >
                <span>{option.id}</span>
                <div><strong>{option.title}</strong><p>{option.description}</p></div>
                <i>{selectedOption === option.id ? '●' : '○'}</i>
              </button>
            ))}
          </div>
          {error && <ErrorPanel text={error} />}
          <Actions>
            <button className="back" onClick={() => setStage('compare')}>← {t.back}</button>
            <button className="primary" disabled={!selectedOption} onClick={() => void rank()}>
              <span>{t.rank}</span><b>→</b>
            </button>
          </Actions>
        </Screen>
      )}

      {stage === 'result' && ranking && generated && (
        <Screen code="04" title={t.resultTitle}>
          <div className="result-summary">
            <div><small>{t.youChose}</small><b>{selectedOption}</b></div>
            <div><small>{t.modelTop}</small><b>{ranking.topOption}</b></div>
          </div>
          <section className="compare-panel">
            <p className="panel-label">{t.rankingLabel}</p>
            <div className="ranking-list">
              {ranking.rankedOptions.map((option) => (
                <div key={option.id} className={option.id === selectedOption ? 'picked' : ''}>
                  <span>#{option.rank}</span>
                  <div>
                    <b>{option.id} · {option.title}{option.id === selectedOption ? ` ← ${t.youChose}` : ''}</b>
                    <i style={{ width: percent(option.probability) }} />
                  </div>
                  <strong>{percent(option.probability)}</strong>
                </div>
              ))}
            </div>
          </section>
          <p className={`alignment ${selectedOption === ranking.topOption ? '' : 'differ'}`}>
            {selectedOption === ranking.topOption ? t.matched : t.differed}
          </p>
          <Distribution dashboard={dashboard} label={t.group} />
          <Actions>
            <button className="primary" onClick={reset}><span>{t.restart}</span><b>↺</b></button>
          </Actions>
        </Screen>
      )}
    </main>
  )
}

function Screen({ code, title, intro, children }: {
  code: string
  title: string
  intro?: string
  children: React.ReactNode
}) {
  return (
    <section className="screen">
      <header className="screen-heading">
        <p className="eyebrow">{code}</p>
        <h2>{title}</h2>
        {intro && <p>{intro}</p>}
      </header>
      <div className="screen-content">{children}</div>
    </section>
  )
}

function Actions({ children }: { children: React.ReactNode }) {
  return <div className="navigation">{children}</div>
}

function Distribution({ dashboard, label }: { dashboard: Dashboard; label: string }) {
  return (
    <section className="distribution">
      <div><span>{label}</span><small>{dashboard.responses}</small></div>
      <div className="distribution-bars">
        {(['A', 'B', 'C'] as OptionId[]).map((id) => (
          <div key={id}>
            <b>{id}</b>
            <i><span style={{ width: percent(dashboard.distribution[id]) }} /></i>
            <strong>{percent(dashboard.distribution[id])}</strong>
          </div>
        ))}
      </div>
    </section>
  )
}

function ErrorPanel({ text }: { text: string }) {
  return <div className="error-panel"><span>!</span><p>{text}</p></div>
}

function FacilitatorView({ dashboard, language, setLanguage }: {
  dashboard: Dashboard
  language: Language
  setLanguage: (language: Language) => void
}) {
  const t = copy[language]
  const metrics = [
    [t.responses, String(dashboard.responses)],
    [t.alignment, percent(dashboard.alignmentRate)],
    [t.confidence, percent(dashboard.averageConfidence)],
  ]
  return (
    <main className="facilitator-shell">
      <header>
        <div><p className="eyebrow">DECISION / ROOM</p><h1>{t.facilitator}</h1></div>
        <button className="language" onClick={() => setLanguage(language === 'en' ? 'el' : 'en')}>
          {language === 'en' ? 'ΕΛ' : 'EN'}
        </button>
      </header>
      {dashboard.responses === 0 ? (
        <div className="waiting"><span /><h2>{t.waiting}</h2></div>
      ) : (
        <>
          <section className="metric-grid">
            {metrics.map(([label, value], index) => (
              <article key={label}><span>0{index + 1}</span><p>{label}</p><strong>{value}</strong></article>
            ))}
          </section>
          <Distribution dashboard={dashboard} label={t.group} />
        </>
      )}
    </main>
  )
}

export default App
